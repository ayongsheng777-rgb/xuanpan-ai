/**
 * 大六壬十二宫在屏幕上的摆位（十二宫方图）。
 *
 * 这是**纯展示顺序**，不是领域规则：十二宫的地盘支 / 天盘支 / 天将全部来自
 * 服务端 `palaces` 数组，本文件只决定它们在 4×4 网格里各占哪一格。
 *
 * 传统摆法是「十二宫方图」，地支沿外圈**顺时针**排列，中央 2×2 空出：
 *
 * ```text
 *   巳 │ 午 │ 未 │ 申
 *  ────┼────┼────┼────
 *   辰 │    │    │ 酉
 *  ────┼────┼────┼────
 *   卯 │    │    │ 戌
 *  ────┼────┼────┼────
 *   寅 │ 丑 │ 子 │ 亥
 * ```
 *
 * 照传统摆，用户才能把屏幕上的课与纸质盘、书上的课直接对照。
 * 外圈顺时针 = 子丑寅卯…亥 的自然顺序，一旦摆反（逆时针），
 * 十二宫仍一个不少地渲染出来、只是整体镜像 —— **不报错**，
 * 用户照着看会得到方向完全错误的判断。
 *
 * 之所以单列成文件并单独接受校验（`tests/mobile/test_liuren_layout.py`），
 * 就是为了让"摆反了"这件事有个会红的地方。
 */

