/**
 * 奇门九宫在屏幕上的摆位（洛书格局）。
 *
 * 这是**纯展示顺序**，不是领域规则：宫序 1~9 及其全部属性都来自服务端
 * `palaces` 数组，本文件只决定它们在 3×3 网格里各占哪一格。
 *
 * 传统排法是 **南上北下**（与地图相反）。照传统摆，用户才能把屏幕上的盘
 * 与纸质盘、书上的盘直接对照；按地图摆（北上南下）会让每一个方位都反着看，
 * 而盘面本身看起来完全正常。
 *
 * 之所以单列成文件并单独接受校验（`tests/mobile/test_qimen_layout.py`）：
 * 这张表写错**不会报错** —— 九个宫仍然一个不少地渲染出来，只是方位整体错位。
 * 用户照着看，会得到一个方向完全错误的结论，且没有任何提示。
 */

/**
 * 洛书九宫格（行优先，南上北下）：
 *
 * ```text
 *   4 巽 │ 9 离 │ 2 坤
 *  ──────┼──────┼──────
 *   3 震 │ 5 中 │ 7 兑
 *  ──────┼──────┼──────
 *   8 艮 │ 1 坎 │ 6 乾
 * ```
 */
export const QIMEN_GRID: readonly number[] = [4, 9, 2, 3, 5, 7, 8, 1, 6];

/**
 * 与 `QIMEN_GRID` 一一对应的屏幕方位。
 *
 * 存在的意义有两个：
 * 1. 无障碍标签 —— 屏幕阅读器用户拿不到"在九宫格的哪个位置"这个信息
 * 2. 校验 —— 服务端每个宫都带 `direction`，两者必须逐位对上，
 *    相当于用**另一条独立路径**核这张表，而不是自己和自己对答案
 */
export const QIMEN_GRID_DIRECTION: readonly string[] = [
  '东南', '南', '西南',
  '东', '中', '西',
  '东北', '北', '西北',
];
