/**
 * 「操作与运作讲解」文案 —— 每个功能页右上角那个问号展开的内容。
 *
 * 为什么要有这一层，而不是把说明写进页面里：
 * 本产品的绝大多数误解都不来自"不会用"，而来自**不知道它在算什么**。
 * 用户以为"AI 在算命"，实际是"代码在算、AI 在解释"；用户以为"识别出来就是结果"，
 * 实际是"识别只给出鱼丝线，坐向必须由人确认"。这些认知差一旦存在，
 * 界面做得再好也会被误读成别的东西。
 *
 * 于是把讲解拆成两块，与页面本身分离：
 *   - `steps` 怎么操作 —— 页面自己也会提示，但这里给完整链路
 *   - `how`  背后怎么运作 —— 页面里放不下，也不该打断操作流
 *
 * ⚠️ 维护约定：**本文件的描述必须与实现一致**。页面改了流程、计算层改了口径，
 * 这里要同步改。文案与实现不一致，比没有文案更糟 —— 它会让人按错的模型去理解结果。
 */

