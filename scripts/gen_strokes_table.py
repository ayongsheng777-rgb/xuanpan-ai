ALL_ROWS = SURNAMES + GIVEN_NAME_CHARS


def build() -> tuple[dict[str, int], list[str]]:
    """构建表并检测冲突。返回 (表, 冲突描述列表)。"""
    table: dict[str, int] = {}
    conflicts: list[str] = []

    for ch, strokes in ALL_ROWS:
        if len(ch) > 1:
            # 复姓：逐字加入，笔画以字为准（复姓整体值不参与查表）
            for c in ch:
                if c not in table:
                    conflicts.append(f"复姓「{ch}」中的「{c}」无单字笔画数据")
                else:
                    table[c] = table.get(c, 0)
            continue
        if not isinstance(strokes, int) or strokes <= 0 or strokes > 64:
            conflicts.append(f"「{ch}」笔画非法：{strokes}")
            continue
        if ch in table and table[ch] != strokes:
            conflicts.append(f"「{ch}」笔画冲突：已有 {table[ch]}，新给 {strokes}")
            continue
        table[ch] = strokes

    # 锚点校验：这 10 个字的笔画是姓名学的硬性常识，作为回归基线
    anchors = {"王": 4, "张": 11, "刘": 15, "陈": 16, "罗": 20, "苏": 22, "谭": 19, "薛": 19, "钱": 16, "赵": 14}
    for ch, expect in anchors.items():
        if table.get(ch) != expect:
            conflicts.append(f"锚点校验失败：「{ch}」应为 {expect}，实为 {table.get(ch)}")

    return table, conflicts


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="只校验，不写文件")
    args = parser.parse_args()

    table, conflicts = build()

    print(f"收录字数: {len(table)}")
    dist: dict[int, int] = {}
    for v in table.values():
        dist[v] = dist.get(v, 0) + 1
    print(f"笔画范围: {min(table.values())} ~ {max(table.values())}")
    print("笔画分布:", " ".join(f"{k}画×{v}" for k, v in sorted(dist.items())))

    if conflicts:
        print("\n❌ 发现冲突，未写入：")
        for c in conflicts:
            print("  -", c)
        return 1

    payload = {
        "version": "1.0-partial",
        "verified": False,
        "stroke_system": "kangxi",
        "generated_by": "scripts/gen_strokes_table.py",
        "note": (
            "V1 部分覆盖：常见姓氏 + 高频名字用字，按姓名学通行的康熙字典笔画计数"
            "（张=張11、刘=劉15、陈=陳16、罗=羅20、苏=蘇22、谭=譚19、薛=19、钱=錢16）。"
            "本表由脚本生成以保证去重与锚点一致，尚未与权威字书逐条比对。"
            "未收录字由 analyze_name 显式报错并列出缺字，不静默取错值。"
            "正式发布前应替换为经校对的完整康熙笔画表，并保留 tests 中的锚点用例。"
        ),
        "total": len(table),
        "anchors": ["王", "张", "刘", "陈", "罗", "苏", "谭", "薛", "钱", "赵"],
        "strokes": {k: table[k] for k in sorted(table)},
    }

    if args.check:
        print("\n✓ 校验通过（--check，未写入）")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    with TARGET.open("w", encoding="utf-8") as fh:
        json.dump(payload, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print(f"\n✓ 已写入 {TARGET.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
